import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {files} from './files.mjs';
export const root=new URL('../',import.meta.url);
export async function precacheFiles(){
  return (await files(root)).filter(path=>['index.html','config.js','manifest.webmanifest','favicon.svg','sw.js'].includes(path)||/^(?:core|ui|assets|data|schemas)\//.test(path)||/^(?:app|agents|privacy)\/.*\.html$/.test(path)||['llms.txt','llms-full.txt','README.md','LICENSE'].includes(path)).filter(path=>path!=='app/_shell.html').sort();
}
export async function precacheSource(){
  const paths=await precacheFiles(),hash=createHash('sha256');for(const path of paths){hash.update(path);hash.update(await readFile(new URL(path,root)));}
  return `// Generated by scripts/build-precache.mjs.\nexport const VERSION = 'waypost-${hash.digest('hex').slice(0,16)}';\nexport const PRECACHE = ${JSON.stringify(paths,null,2)};\n`;
}
